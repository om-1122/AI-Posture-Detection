import streamlit as st
import os
import json
import time
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI


# ==========================================
# LOAD ENVIRONMENT VARIABLES
# ==========================================

BASE_DIR = Path(__file__).resolve().parent

load_dotenv(BASE_DIR / ".env", override=True)


# ==========================================
# GROQ CLIENT
# ==========================================

def get_groq_client():

    try:
        api_key = st.secrets["GROQ_API_KEY"]
    except Exception:
        api_key = os.getenv("GROQ_API_KEY")

    if not api_key:
        raise ValueError(
            "GROQ_API_KEY is missing. Check your Streamlit Secrets or .env file."
        )

    return OpenAI(
        api_key=api_key,
        base_url="https://api.groq.com/openai/v1"
    )

# ==========================================
# GENERATE POSTURE REPORT
# ==========================================

def generate_posture_report(measurements):

    client = get_groq_client()

    model = os.getenv(
        "GROQ_MODEL",
        "openai/gpt-oss-120b"
    )

    prompt = f"""
You are an AI assistant that explains human posture
measurements in clear and understandable language.

Analyze the following measurements generated by
a Python MediaPipe posture detection system.

MEASUREMENTS:

{json.dumps(measurements, indent=2)}

Generate a detailed report with these sections:

1. OVERALL POSTURE ASSESSMENT
   - Potentially good
   - Potentially needs improvement
   - Insufficient information

2. BODY ALIGNMENT
   Explain measured joint angles and body alignment.

3. POSITIVE OBSERVATIONS
   Explain positive features supported by measurements.

4. POSSIBLE DISADVANTAGES
   Explain possible ergonomic concerns.

5. IMPROVEMENT SUGGESTIONS
   Give practical and safe recommendations.

6. POSSIBLE FUTURE CONCERNS
   Explain possible discomfort or ergonomic issues.

7. MEASUREMENT LIMITATIONS
   Explain unavailable measurements and camera limitations.

IMPORTANT RULES:

- Never invent missing measurements.
- Never treat missing measurements as zero.
- Do not assume a front or side camera view.
- Do not use universal angle thresholds to diagnose posture.
- Consider sitting, standing, bending or other activities.
- Distinguish measured facts from interpretations.
- Do not diagnose diseases or predict injuries.
- Do not claim that one photograph proves good or bad health.
- If evidence is insufficient, clearly say so.
- Explain that a single image cannot assess movement,
  pain or long-term posture habits.

Write the report with clear headings and bullet points.
Use simple language suitable for a student project.
"""

    # ======================================
    # GROQ API REQUEST WITH RETRIES
    # ======================================

    response = None

    for attempt in range(3):

        try:

            response = client.chat.completions.create(

                model=model,

                messages=[

                    {
                        "role": "system",

                        "content": (
                            "You are a careful posture analysis "
                            "assistant. Follow all measurement "
                            "limitations and safety instructions."
                        )
                    },

                    {
                        "role": "user",

                        "content": prompt
                    }

                ],

                temperature=0.3,

                max_tokens=3000
            )

            break

        except Exception as e:

            error_message = str(e).upper()

            if any(code in error_message for code in [
                "503",
                "502",
                "500",
                "UNAVAILABLE"
            ]):

                if attempt < 2:

                    wait_time = 3 * (attempt + 1)

                    print(
                        f"Groq temporarily unavailable. "
                        f"Retrying in {wait_time} seconds..."
                    )

                    time.sleep(wait_time)

                else:

                    raise RuntimeError(
                        "Groq server is temporarily unavailable."
                    ) from e

            else:

                raise

    # ======================================
    # CHECK RESPONSE
    # ======================================

    if (
        response is None
        or not response.choices
        or not response.choices[0].message.content
    ):

        raise RuntimeError(
            "Groq returned an empty response."
        )

    return response.choices[0].message.content
